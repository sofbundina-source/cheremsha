/*
  =============================================================================
  🎯 КОНТРОЛЬНАЯ ТОЧКА: «ЛАБИРИНТ ХРАНИТЕЛЯ»
  =============================================================================

  Ваша задача — написать текстовую игру, которая запускается в браузере.
  Игрок исследует комнаты, собирает предметы и ищет путь к главному боссу - черемшонищу.
  Можно играть компанией за одним компьютером и вместе выбирать действия.

  Для победы нужно найти:
  - «ключоныш» — открывает дверь в зал босса;
  - «черемша» — усиливает героя перед боем;
  - «бурмалдуйский меч» — позволяет ранить босса;
  - «масло семги» — защищает от его магии.

  Главное в этой работе — продумать переходы между комнатами, вложенные
  условия и проверки содержимого рюкзака.

  =============================================================================
  🗺️ 1. ПРИДУМАЙТЕ ЛАБИРИНТ
  =============================================================================

  Перед написанием кода нарисуйте схему на бумаге.
  В лабиринте должно быть не менее 7 комнат. Предметы лежат в разных комнатах.
  Хотя бы один путь должен содержать 3 перехода подряд от входа.
  Из каждой комнаты, кроме финала после боя, можно вернуться назад.

  Пример схемы, которую можно использовать или изменить:

  Вход
  ├── Аккуратный коридор
  │   └── Библиотека
  │       └── Тайник-ВнутрьНеПроник [ключоныш]
  └── Шующий коридор
      ├── Сад-бурмалдат [черемша]
      ├── Оружейная-кондицейная [бурмалдуйский меч]
      ├── Святилище-бурмалдинище [масло семги]
      └── Зал босса [дверь открывается ключонышем]

  Комнаты внутри других комнат не нужно хранить в массивах.
  Достаточно переменной room с названием текущей комнаты.
  Например, после выбора двери: room = «библиотека».
  На следующем повторении цикла программа покажет меню библиотеки.

  =============================================================================
  🎒 2. ДОБАВЬТЕ ПРЕДМЕТЫ И РЮКЗАК
  =============================================================================

  - Рюкзак — обычный массив inventory, изначально пустой.
  - В комнате с предметом предложите взять его через confirm().
  - При согласии добавьте предмет в рюкзак методом push().
  - При отказе оставьте предмет: игрок сможет вернуться за ним позже.
  - Повторно получить тот же предмет нельзя. Перед предложением взять вещь
    проверьте через includes(), нет ли её уже в рюкзаке.
  - Функция showInventory() уже написана: она показывает вещи в рюкзаке.
    Её можно вызвать из меню у входа. Посмотрите, как она проверяет массив.

  Во всём коде используйте одинаковые названия предметов:
  «ключоныш», «черемша», «бурмалдуйский меч», «масло семги».

  =============================================================================
  🚪 3. ПРОДУМАЙТЕ ВЛОЖЕННЫЕ УСЛОВИЯ У ДВЕРИ БОССА
  =============================================================================

  Проверки должны происходить последовательно:

  1. Игрок выбирает проход к боссу. Есть ли в рюкзаке ключоныш?
     Нет — показать сообщение о запертой двери и оставить игрока снаружи.
     Да — разрешить перейти в зал босса.

  2. В зале предложите начать бой или вернуться за недостающими предметами.
     Само посещение зала ещё не запускает бой.

  3. Только если игрок выбрал бой, проверьте снаряжение:
     - есть бурмалдуйский меч, черемша И масло семги — победа;
     - хотя бы одного из этих предметов нет — поражение.

  После победы или поражения завершите игровой цикл с помощью break.
  В начале игры обязательно покажите список того, что нужно найти.

  =============================================================================
  💡 НЕБОЛЬШИЕ ПОДСКАЗКИ
  =============================================================================

  inventory.push("верёвка");          // Добавить вещь.
  inventory.includes("верёвка");      // Есть ли вещь? true или false.
  inventory.length === 0;             // Пустой ли рюкзак?
  inventory.join(", ");               // Получить строку со списком вещей.

  && означает «И»: для успеха должны выполняться оба условия.
  Пример вложенных проверок на другую тему:

  if (age >= 12) {
      if (hasTicket === true) {
          alert("Можно войти!");
      } else {
          alert("Нужен билет.");
      }
  } else {
      alert("Пока рано.");
  }

  prompt() возвращает строку, поэтому сравнивайте выбор с "1", а не с 1.
  При нажатии «Отмена» prompt() возвращает null.
  confirm() возвращает true при «ОК» и false при «Отмена».
  while (true) повторяет меню; break завершает этот цикл.

  ДОПОЛНИТЕЛЬНО, ЕСЛИ ОСНОВНАЯ ИГРА УЖЕ РАБОТАЕТ:
  - При победе израсходуйте траву: найдите её индекс через indexOf()
    и удалите методом splice(). Перед удалением проверьте, что индекс не -1.
  - Придумайте одну дополнительную дверь с условием или альтернативный финал.

  =============================================================================
  ✅ ЧТО ПОКАЗАТЬ ПРИ СДАЧЕ
  =============================================================================

  Продемонстрируйте: путь через несколько комнат; возврат назад; отказ взять
  предмет и возвращение за ним; защиту от повторного сбора; запертую дверь;
  победу со всеми предметами и поражение без одного из них.

  Объясните одно своё вложенное условие и одну проверку рюкзака.

  Ниже полностью готов один маршрут:
  вход → аккуратный коридор → библиотека → тайник-ВнутрьНеПроник с ключонышом
  Можно пройти до тайника-ВнутрьНеПроника, взять ключоныш и вернуться ко входу.

  У каждой комнаты свой блок: сначала prompt(), затем проверки выбора.
  Для новой комнаты добавьте ещё один else if по образцу готовых комнат.
  Восточную ветку, остальные предметы и босса напишите самостоятельно.

  Для запуска подключите файл в HTML: <script src="dungeon-quest.js"></script>
*/

const inventory = [];
let room = "врата";

function showInventory() {
    if (inventory.length === 0) {
        alert("Рюкзак пуст. Даже пыли не набрали.");
    } else {
        alert("В рюкзаке: " + inventory.join(", "));
    }
}

alert(
    "ПРОКЛЯТИЕ БУРМАЛДУЙСКОЙ ЛАБОРАТОРИИ\n\n" +
    "Шлепокрыл Черемшонищь пробудился!\n" +
    "Чтобы победить его найдите:\n\n" +
    "ключоныш, черемшулю, бурмалдуйский мечок и маслице семги.\n\n" +
    "Исследуйте лабораторию и спасите бурмалдуйщину"
);


while (true) {
    if (room === "врата") {
        const choice = prompt(
            "Врата бурмалдуйщины\n" +
            "1 — Шующий коридор\n" +
            "2 — Тоннель зеленых испарений\n" +
            "3 — Проверить рюкзак\n" +
            "0 — Выйти из игры"
        );

        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            room = "Шующий коридор";
        } else if (choice === "2") {
            room = "Тоннель зеленых испарений";
        } else if (choice === "3") {
            showInventory();
        } else {
            alert("Такого прохода нет.");
        }
    }

    else if (room === "Шующий коридор") {
        const choice = prompt(
            "ШУЮЩИЙ КОРИДОР\n" +
            "1 — Архив древних бурмалдуев\n" +
            "2 — Вернуться к вратам\n" +
            "0 — Выйти из игры"
        );

        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            room = "архив";
        } else if (choice === "2") {
            room = "врата";
        } else {
            alert("Такого прохода нет.");
        }
    }

    else if (room === "архив") {
        const choice = prompt(
            "АРХИВ ДРЕВНИХ БУРМАЛДУЕВ\n" +
            "1 — Открыть секретную кладовку\n" +
            "2 — Вернуться в шующий коридор\n" +
            "0 — Выйти из игры"
        );

        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            room = "кладовка";
        } else if (choice === "2") {
            room = "Шующий коридор";
        } else {
            alert("Такого прохода нет.");
        }
    }

    else if (room === "кладовка") {
        const choice = prompt(
            "СЕКРЕТНАЯ КЛАДОВКА КЛЮЧОНЫШЕЙ\n" +
            "1 — Осмотреть сундук\n" +
            "2 — Вернуться в архив\n" +
            "0 — Выйти из игры"
        );

        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            if (inventory.includes("ключоныш")) {
                alert("Сундук пуст. Ключоныш уже у вас.");
            } else {
                const takeKey = confirm("В сундуке лежит ключоныш. Забрать его?");

                if (takeKey === true) {
                    inventory.push("ключоныш");
                    alert("Ключоныш добавлен в рюкзак!");
                } else {
                    alert("Вы оставили ключоныш в сундуке.");
                }
            }
        } else if (choice === "2") {
            room = "архив";
        } else {
            alert("Такого действия нет.");
        }
    }
    else if (room === "тоннель") {
        const choice = prompt(
            "ТОННЕЛЬ ЗЕЛЕННЫХ ИСПАРЕНИЙ\n" +
            "1 — Теплица черемшуль\n" +
            "2 — Кузница мечей\n" +
            "3 — Алтарь семгово масла\n" +
            "4 — Дверь в тронный зал\n" +
            "5 — Вернуться к вратам\n" +
            "0 — Выйти из игры"
        );
        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            room = "теплица";
        } else if (choice === "2") {
            room = "кузница";
        } else if (choice === "3") {
            room = "алтарь";
        } else if (choice === "4") {
            if (inventory.includes("ключоныш")) {
                room = "тронный зал";
            } else {
                alert("Дверь заперта! Найдите ключоныш.");
            }
        } else if (choice === "5") {
            room = "врата";
        } else {
            alert("Такого прохода нет.")
        }
    }
    else if (room === "теплица") {
        const choice = prompt(
            "ТЕПЛИЦА ЧЕРЕМШУЛЬ\n" +
            "1 — Собрать черемшулю\n" +
            "2 — Вернуться в тоннель\n" +
            "0 — Выйти из игры"
        );
        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            if (inventory.includes("черемшуля")) {
                alert("Черемшуля уже у вас.")
            }
        } else {
            const takeItem = confirm("На грядке растет магическая черемшуля. Взять ее?"
            );
            if (takeItem === true) {
                inventory.push("черемшуля");
                alert("Черемшуля добавлена в рюкзак!");
            } else {
                alert("Вы оставили черемшулю на грядке.")
            }
        }
    } else if (choice === "2") {
        room = "тоннель";
    }
    else if (room === "кузница") {
        const choice = prompt(
            "КУЗНИЦА МЕЧЕЙ\n" +
            "1 — Осмотреть наковальню\n" +
            "2 — Вернуться в тоннель\n" +
            "0 — Выйти из игры"
        );
        if (choice === "0" || choice === null) {
            break;
        } else if (choice === "1") {
            if (inventory.includes("бурмалдуйский меч")) {
                alert("Бурмалдуйский меч уже у вас!");
            } else {
                const takeItem = confirm("На наковальне лежал бурмалдуйский  меч. Взять?");
                if (takeItem == true) {
                    inventory.push("бурмалдуйский меч");
                    alert("Вы получили бурмалдуйский меч!");
                } else {
                    alert("Вы оставили меч в кузнице.");
                }
            }
        } else if (choice === "2") {
            room = "тоннель";
        } else {
            alert("Такого действия нет.")
        }

    }
}